Z-Image Turbo prompt guide

Model behavior
Z-Image Turbo is a fast, instruction-following image model with strong English
and Chinese text rendering. It responds best to direct camera and art-direction
language. Treat the prompt as a description of the finished image.

Affirmative prompt structure
Build the prompt from concrete desired details:
1. Image type and framing
2. Subject identity, age, appearance, and pose
3. Clothing and color palette
4. Environment and composition
5. Lighting and mood
6. Medium, lens, and rendering details
7. Desired safety, anatomy, and finish qualities

Composition
Use precise shot language such as close-up, medium shot, full-body, wide shot,
front view, 45-degree angle, or profile. State the number of subjects and their
placement. Use single-subject composition, equal framing, centered composition,
or balanced group composition when those qualities matter.

Subject and continuity
Describe each subject with a role plus a few observable traits. Keep recurring
names, facial features, body proportions, wardrobe, accessories, and palette
consistent across related images. Specify adults explicitly when depicting
adults.

Clothing and safety
Describe the exact desired wardrobe and coverage: tailored business suit,
long-sleeved shirt and trousers, jeans and a hoodie, modest evening dress, or
another concrete outfit. Useful desired-state phrases include fully clothed,
family-friendly, professional, respectful, everyday context, and anatomically
accurate natural hands.

Environment and clean finish
Describe the intended background directly: plain studio backdrop, softly
blurred office, uncluttered room, open landscape, or balanced city street.
Useful finish phrases include crisp focus, clean detailed image, natural body
proportions, coherent perspective, polished unbranded presentation, blank
surfaces, and a purely visual composition.

Lighting, mood, and medium
Choose a clear lighting setup such as soft diffused daylight, cinematic warm
key light, cool ambient light, high-contrast noir lighting, studio portrait
lighting, rim lighting, or split lighting. Pair it with a specific mood and one
medium such as realistic photography, flat vector illustration, watercolor,
manga, pixel art, or a cinematic film still.

Text rendering
When visible text is requested, quote the exact approved text and describe its
language, placement, typography, scale, and color. Phrases such as "the title is
the sole visible lettering" or "blank packaging with a simple generic symbol"
keep the desired composition explicit.

Prompt length
Prefer a concise, structured description over poetic prose. Roughly 80-250
words is enough for most detailed scenes. Include only details that visibly
change the result.

Example: professional portrait
A medium-shot portrait of an adult woman in her 30s with medium-length brown
hair, wearing a dark tailored business suit and shirt, fully clothed in a modest
