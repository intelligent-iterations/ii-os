photography, 50mm lens, shallow depth of field, crisp focus, clean unbranded
presentation, purely visual composition.

Example: diverse group
A medium-wide portrait of five adult coworkers with individualized features,
diverse ethnicities, genders, ages, and realistic body types, wearing smart
casual outfits in an open-plan office, relaxed professional expressions, equal
framing, soft daylight from large windows, respectful family-friendly realism,
